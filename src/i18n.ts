const STRINGS: Record<Lang, Record<Key, string>> = { zh, en };

/** 仅供测试 */
export const _strings = STRINGS;

let uiLang: Lang = "en";

/** Obsidian 语言代码 → 支持的语言；中文（含繁体）用简体，其他用英文 */
export function toLang(code: string | null | undefined): Lang {
  return code?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function setUiLang(lang: Lang): void {
  uiLang = lang;
}

export function getUiLang(): Lang {
  return uiLang;
}

export function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function tr(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  return format(STRINGS[lang][key], vars);
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  return tr(uiLang, key, vars);
}
